"use strict";
/**
 * Ярлыки: «от головы», «от температуры», «детское».
 *
 * Зачем они нужны. Аптечку открывают в тот момент, когда болит, а не
 * когда её заводили. Поиск по названию работает, только если название
 * помнишь, — а помнят его редко: коробку покупали год назад и по совету.
 * Ярлык — это подпись на полке, сделанная своей рукой.
 *
 * ГРАНИЦА, и она здесь важнее всего остального в файле.
 * Ярлык пишет человек. Сервис его не подставляет: ни из официальной
 * инструкции, ни из общего каталога, ни со снимка вкладыша. Иначе строка
 * «от головы» перестала бы быть чужой пометкой на коробке и стала бы
 * показанием к применению, выданным сервисом, — а сервис ведёт учёт и не
 * лечит (ARCHITECTURE.md, «Граница»). По той же причине ярлыки не уезжают
 * в общий каталог: это и подсказка, которую мы не вправе давать, и утечка
 * — по «от давления» и «для Маши» читается слишком много.
 *
 * Общий файл сервера и браузера — как expiry.js и gs1.js: гость и
 * вошедший обязаны склеивать «От головы» и «от головы» одинаково, иначе
 * при первом входе аптечка приедет с удвоенными ярлыками.
 */
(function (root) {
  /** На ярлык и на позицию. Пределы не про память, а про то, что список из
   *  тридцати ярлыков искать тяжелее, чем список из тридцати упаковок. */
  const TAG_MAX = 24;
  const PER_ITEM = 8;

  /**
   * Ключ для сравнения. Регистр средствами JS, а не SQLite: lower() там
   * работает только для латиницы — тот же урок, что с name_key в store.js.
   * «ё» приравнена к «е»: «зелёнка» и «зеленка» — один ярлык, и человек не
   * должен помнить, как он написал его в первый раз.
   */
  const key = s => String(s ?? "").toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim();

  /**
   * Привести к списку ярлыков то, что прислал клиент или ввела форма:
   * массив, либо строка через запятую. Показываем так, как написали, а
   * сравниваем по ключу.
   */
  function norm(v) {
    const raw = Array.isArray(v) ? v
      : typeof v === "string" ? v.split(/[,;\n]/)
        : [];
    const out = [];
    const seen = new Set();
    for (const item of raw) {
      // Обрезаем, а не отбрасываем: человек дописал лишнее слово — ярлык
      // всё равно его, терять его молча хуже, чем укоротить.
      const s = String(item ?? "").replace(/\s+/g, " ").trim().slice(0, TAG_MAX).trim();
      const k = key(s);
      if (!k || seen.has(k)) continue;
      seen.add(k);
      out.push(s);
      if (out.length >= PER_ITEM) break;
    }
    return out;
  }

  /** Объединение: добавить ярлыки, ничего не потеряв. Порядок прежних сохраняется. */
  const merge = (a, b) => norm([...norm(a), ...norm(b)]);

  const has = (tags, k) => norm(tags).some(t => key(t) === key(k));

  /**
   * С чего начать. Это названия пустых полок, а не утверждения о
   * препаратах: что на какую полку положить, решает человек. Поэтому
   * список можно показывать всем и он ничего не советует.
   */
  const SUGGEST = [
    "от головы", "от температуры", "от простуды", "от горла",
    "от живота", "от аллергии", "от давления", "обезболивающее",
    "антисептик", "перевязка", "детское", "витамины",
  ];

  const T = { TAG_MAX, PER_ITEM, key, norm, merge, has, SUGGEST };
  if (typeof module === "object" && module.exports) module.exports = T;
  else root.ZapasTags = T;
})(typeof globalThis !== "undefined" ? globalThis : this);
