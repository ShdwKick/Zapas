"use strict";
/**
 * Сверка цитат с текстом документа — общий файл сервера, инструмента и фронта.
 *
 * На этом стоит всё извлечение данных из инструкций: модель называет поле и
 * приводит дословную цитату, а мы проверяем, что цитата в документе
 * действительно есть. Не нашлась — поля не будет. Так выдуманное значение
 * отсеивается технически, а не «с высокой вероятностью».
 *
 * Чего проверка НЕ ловит, и об этом надо писать в интерфейсе: если документ
 * — фотография, то текстом мы считаем то, что распознала сама модель. Тогда
 * сверка показывает, что модель не придумала факт сверх прочитанного, но не
 * доказывает, что цифру она прочитала верно.
 */
(function (root) {
  /**
   * Приведение к виду, в котором можно искать подстроку.
   *
   * Два правила, оба найдены на живой инструкции, а не придуманы:
   *  - переносы: в PDF встречается «при темпе - ратуре», модель склеивает
   *    правильно, и наивный поиск подстроки промахивается;
   *  - пробелы: их расстановка в PDF своя, сравнивать по ним нельзя.
   */
  function normalize(s) {
    return String(s || "")
      .replace(/­/g, "")
      .replace(/(\p{L})\s*-\s+(\p{L})/gu, "$1$2")
      .replace(/\s+/g, "")
      .toLowerCase();
  }

  /**
   * Есть ли цитата в тексте документа.
   *
   * Минимальная длина — защита от цитат вроде «3 года», которые найдутся в
   * любом документе и ничего не подтверждают.
   */
  function quoteFound(quote, text) {
    const q = normalize(quote);
    return q.length >= 8 && normalize(text).includes(q);
  }

  const Q = { normalize, quoteFound };
  if (typeof module === "object" && module.exports) module.exports = Q;
  else root.ZapasQuotes = Q;
})(typeof globalThis !== "undefined" ? globalThis : this);
