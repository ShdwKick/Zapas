// Правила ярлыков: склейка, пределы, сравнение. Общий файл сервера и
// браузера, поэтому чистые функции.                node test/tags.test.mjs
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const T = require("../assets/tags.js");

let fails = 0;
const eq = (name, got, want) => {
  const ok = JSON.stringify(got) === JSON.stringify(want);
  if (!ok) fails++;
  console.log(`${ok ? "ок  " : "FAIL"} ${name}${ok ? "" : `: получили ${JSON.stringify(got)}, ждали ${JSON.stringify(want)}`}`);
};

{ // ключ сравнения
  eq("регистр не важен", T.key("От Головы"), "от головы");
  eq("пробелы сжимаются", T.key("  от   головы  "), "от головы");
  eq("ё приравнена к е", T.key("Зелёнка"), T.key("зеленка"));
  eq("пусто остаётся пустым", T.key(null), "");
}

{ // приведение списка
  eq("массив как есть", T.norm(["от головы", "детское"]), ["от головы", "детское"]);
  eq("строка через запятую", T.norm("от головы, детское"), ["от головы", "детское"]);
  eq("точка с запятой и перевод строки", T.norm("а;б\nв"), ["а", "б", "в"]);
  eq("пустые отбрасываются", T.norm("от головы, , ,"), ["от головы"]);
  eq("мусор на входе — пустой список", [T.norm(null), T.norm(7), T.norm({})], [[], [], []]);
}

{ /* Дубли. Главное, зачем этот файл общий: гость и сервер обязаны склеивать
     одинаково, иначе при первом входе ярлыки приедут удвоенными. */
  eq("повтор в другом регистре", T.norm(["От головы", "от ГОЛОВЫ"]), ["От головы"]);
  eq("повтор через ё", T.norm(["Зелёнка", "зеленка"]), ["Зелёнка"]);
  eq("первое написание сохраняется", T.norm(["ОТ ГОЛОВЫ", "от головы"])[0], "ОТ ГОЛОВЫ");
}

{ // пределы
  const long = "а".repeat(T.TAG_MAX + 10);
  eq("длинный обрезается, а не теряется", T.norm([long])[0].length, T.TAG_MAX);
  const many = Array.from({ length: T.PER_ITEM + 5 }, (_, i) => "ярлык" + i);
  eq("больше предела не берём", T.norm(many).length, T.PER_ITEM);
  eq("и берём первые", T.norm(many)[0], "ярлык0");
}

{ // объединение и проверка
  eq("объединение без потерь", T.merge(["от головы"], ["детское"]), ["от головы", "детское"]);
  eq("объединение не плодит дубли", T.merge(["от головы"], ["От Головы"]), ["от головы"]);
  eq("порядок прежних сохраняется", T.merge(["б", "а"], ["в"]), ["б", "а", "в"]);
  eq("has не зависит от регистра", T.has(["От головы"], "от ГОЛОВЫ"), true);
  eq("has про чужой ярлык", T.has(["от головы"], "детское"), false);
  eq("has на пустом", T.has(null, "от головы"), false);
}

{ /* Подсказки — названия пустых полок, а не утверждения о препаратах.
     Если в этом списке однажды появится что-то вида «Нурофен — от головы»,
     сервис начнёт советовать, а он ведёт учёт (ARCHITECTURE.md, «Граница»). */
  eq("подсказки есть", T.SUGGEST.length > 0, true);
  eq("подсказки нормализованы", T.norm(T.SUGGEST.slice(0, T.PER_ITEM)), T.SUGGEST.slice(0, T.PER_ITEM));
  eq("каждая влезает в предел", T.SUGGEST.every(t => t.length <= T.TAG_MAX), true);
  eq("дублей среди подсказок нет", new Set(T.SUGGEST.map(T.key)).size, T.SUGGEST.length);
}

console.log(fails ? `\nПровалено: ${fails}` : "\nВсё прошло.");
process.exit(fails ? 1 : 0);
